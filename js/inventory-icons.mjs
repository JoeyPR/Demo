/* Reuse Planner's real inventory-icon renderer and its icon-profile catalog.
   The previous adapter hid failed requests/ID mismatches by drawing '?'.
   Try GitHub Raw first for the large index, then jsDelivr, and log the reason. */
const PLANNER_REVISION = "4d53314439faa2c9f29e971d619b2d8975ae605d";
const PLANNER_ROOT = new URL(`https://cdn.jsdelivr.net/gh/JoeyPR/Planner@${PLANNER_REVISION}/`);
const INDEX_URLS = [
  new URL(`https://raw.githubusercontent.com/JoeyPR/Planner/${PLANNER_REVISION}/data/inventory-index.json`),
  new URL("data/inventory-index.json", PLANNER_ROOT),
];
let runtimePromise = null;
let runtimeFailureLogged = false;
let missingItemWarnings = 0;

function paintFallback(canvas, glyph = "?") {
  const context = canvas.getContext("2d", { alpha: true });
  if (!context) return;
  context.clearRect(0, 0, canvas.width, canvas.height);
  context.fillStyle = "#d9edf5";
  context.font = "bold 18px sans-serif";
  context.textAlign = "center";
  context.textBaseline = "middle";
  context.fillText(glyph, 16, 16);
}

function idKey(value) {
  const text = String(value ?? "").trim();
  if (!text) return "";
  const numeric = Number(text);
  return Number.isSafeInteger(numeric) ? String(numeric) : text.toLocaleLowerCase();
}

function nameKey(value) {
  return String(value ?? "")
    .replace(/`[0123456789!@#$^&wobpqertasc]/g, "")
    .replace(/`/g, "")
    .replace(/s+/g, " ")
    .trim()
    .toLocaleLowerCase();
}

async function fetchInventoryIndex() {
  const failures = [];
  for (const url of INDEX_URLS) {
    try {
      const response = await fetch(url, { cache: "no-store", mode: "cors" });
      if (!response.ok) throw new Error(`HTTP ${response.status}: ${url.href}`);
      const payload = await response.json();
      if (payload?.schemaVersion !== 3 || !Array.isArray(payload.items)) {
        throw new Error(`Unexpected inventory-index schema: ${url.href}`);
      }
      return payload;
    } catch (error) {
      failures.push(error?.message ?? String(error));
    }
  }
  throw new Error("All Planner inventory-index sources failed: " + failures.join(" | "));
}

function loadIconRuntime() {
  if (!runtimePromise) {
    runtimePromise = Promise.all([
      import(new URL("js/inventory/itemIcons.js", PLANNER_ROOT).href),
      fetchInventoryIndex(),
    ]).then(([iconModule, payload]) => {
      const itemsById = new Map();
      const itemsByName = new Map();
      for (const item of payload.items) {
        if (item?.id != null) itemsById.set(idKey(item.id), item);
        const key = nameKey(item?.name);
        if (key && !itemsByName.has(key)) itemsByName.set(key, item);
      }
      if (typeof iconModule.renderInventoryIcon !== "function") {
        throw new Error("Planner's renderInventoryIcon export is missing");
      }
      return { renderInventoryIcon: iconModule.renderInventoryIcon, itemsById, itemsByName, itemCount: payload.items.length };
    }).catch(error => {
      if (!runtimeFailureLogged) {
        console.error("Planner icon runtime could not load. All '?' icons were generated by this fallback.", error);
        runtimeFailureLogged = true;
      }
      throw error;
    });
  }
  return runtimePromise;
}

export async function renderPlannerInventoryIcon(canvas, demoItem) {
  if (!(canvas instanceof HTMLCanvasElement)) return;
  const token = Symbol("planner-icon");
  canvas.__plannerIconToken = token;
  paintFallback(canvas, "…");
  try {
    const runtime = await loadIconRuntime();
    if (canvas.__plannerIconToken !== token) return;
    const item = runtime.itemsById.get(idKey(demoItem?.id))
      ?? runtime.itemsByName.get(nameKey(demoItem?.name));
    if (!item) {
      if (missingItemWarnings < 5) console.warn("No Planner icon metadata matched this Demo item.", {
        id: demoItem?.id, name: demoItem?.name, plannerItemCount: runtime.itemCount
      });
      missingItemWarnings += 1;
      paintFallback(canvas);
      return;
    }
    await runtime.renderInventoryIcon(canvas, item);
  } catch (error) {
    if (canvas.__plannerIconToken === token) paintFallback(canvas);
    if (!runtimeFailureLogged) {
      console.error("Planner inventory icon rendering failed.", {
        id: demoItem?.id, name: demoItem?.name, error
      });
      runtimeFailureLogged = true;
    }
  }
}
